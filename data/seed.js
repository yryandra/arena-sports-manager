const id = (number) => number.toString(16).padStart(24, '0')
const day = (offset) => {
  const date = new Date()
  date.setUTCDate(date.getUTCDate() + offset)
  return new Intl.DateTimeFormat('en-CA', {
    timeZone: 'Asia/Riyadh',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  }).format(date)
}
